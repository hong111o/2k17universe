const { chromium } = require(process.argv[2] + '/node_modules/playwright');
(async () => {
  const [,, pw, html, xlsm, out] = process.argv;
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1400, height: 1000 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.route(/cdnjs\.cloudflare\.com\/ajax\/libs\/xlsx/, r => r.fulfill({ path: pw + '/node_modules/xlsx/dist/xlsx.full.min.js', contentType: 'application/javascript' }));
  await p.route(/fonts\.googleapis/, r => r.abort());
  await p.goto('file://' + html);
  await p.setInputFiles('#fileInput', xlsm);
  await p.waitForSelector('#app', { state: 'visible', timeout: 60000 });
  const r = {};
  const open = async team => { await p.evaluate(t => openTeamModal(t), team); await p.waitForTimeout(200); };
  await open('Washington Wizards');
  r.wasMarks = await p.locator('#winChart circle.wc-mark').count();
  r.wasSeasons = await p.evaluate(() => winChartData.seasons.length);
  await p.locator('#winChart svg').scrollIntoViewIfNeeded(); const box = await p.locator('#winChart svg').boundingBox();
  await p.mouse.move(box.x + box.width - 60, box.y + 80); await p.waitForTimeout(100);
  r.tipHover = (await p.textContent('#winChart .wc-tip')).replace(/\s+/g,' ').trim();
  await p.locator('#teamPage .chart-card').filter({ has: p.locator('#winChart') }).screenshot({ path: out + '/v14-chart-was.png' });
  await p.mouse.move(0, 0);
  await p.focus('#winChart svg'); await p.keyboard.press('ArrowLeft'); await p.keyboard.press('ArrowLeft');
  r.tipKeys = (await p.textContent('#winChart .wc-tip')).replace(/\s+/g,' ').trim();
  r.tableVsChart = await p.evaluate(() => { const s = winChartData.seasons.find(x => x.yr === 2070); return `${s.w}-${s.l} conf#${s.confRk}`; });
  r.tableRow2070 = await p.evaluate(() => [...document.querySelectorAll('.standings-table tbody tr')].find(tr => tr.children[0].textContent === '2069–70')?.innerText.replace(/\s+/g,' '));
  await p.keyboard.press('Escape');
  await open('Los Angeles Lakers');
  await p.locator('#teamPage .chart-card').filter({ has: p.locator('#winChart') }).screenshot({ path: out + '/v14-chart-lal.png' });
  await p.keyboard.press('Escape');
  await open('San Diego Surf'); r.sdSeasons = await p.evaluate(() => winChartData.seasons.map(s => s.yr).join(','));
  r.sdPath = await p.getAttribute('#winChart path.wc-line', 'd').then(d => d.match(/M/g).length + ' segment(s)');
  await p.keyboard.press('Escape');
  await open('Vancouver Ravens'); r.ravensChart = await p.locator('#winChart').count();
  await p.keyboard.press('Escape');
  await p.setViewportSize({ width: 390, height: 800 });
  await open('Detroit Pistons');
  r.phoneSvgW = await p.evaluate(() => [document.querySelector('#winChart svg').getAttribute('width'), document.querySelector('#winChart').clientWidth]);
  await p.locator('#teamPage .chart-card').filter({ has: p.locator('#winChart') }).screenshot({ path: out + '/v14-chart-phone.png' });
  r.errors = errs;
  console.log(JSON.stringify(r, null, 1));
  await b.close();
})();
